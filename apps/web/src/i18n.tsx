type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (text: string) => string;
  value: (text: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => localStorage.getItem('wison-locale') === 'en' ? 'en' : 'zh');
  useEffect(() => {
    localStorage.setItem('wison-locale', locale);
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN';
  }, [locale]);
  const context = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale,
    t: (text) => locale === 'en' ? english[text] ?? text : text,
    value: (text) => locale === 'en' ? valueEnglish[text] ?? generatedValueEnglish[text] ?? text : text,
  }), [locale]);
  return <I18nContext.Provider value={context}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider.');
  return context;
}
