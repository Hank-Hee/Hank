import { createHash } from 'node:crypto';
import { readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(repositoryRoot, 'supabase/seed.sql');

const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const nullable = (value) => value ? quote(value) : 'null';
const textArray = (values) => `array[${values.map(quote).join(', ')}]::text[]`;

const inventory = JSON.parse(
  await readFile(resolve(repositoryRoot, 'data/company-demo-inventory.json'), 'utf8'),
);
const profiles = JSON.parse(
  await readFile(resolve(repositoryRoot, 'company-text-dashboard/data/company-data.json'), 'utf8'),
);
const operatorManifest = JSON.parse(
  await readFile(resolve(repositoryRoot, 'maps/operators.json'), 'utf8'),
);
const reportContext = { window: {} };
vm.runInNewContext(
  await readFile(resolve(repositoryRoot, 'industry-research-data.js'), 'utf8'),
  reportContext,
  { timeout: 1_000 },
);

const normalizeName = (value) => String(value).trim().toLocaleLowerCase('en-US');
const slugify = (value) => String(value)
  .normalize('NFKD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLocaleLowerCase('en-US')
  .replaceAll('&', ' and ')
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '');
const featuredByName = new Map(
  inventory.companies.map((company) => [normalizeName(company.displayName), company]),
);
const operatorByName = new Map(
  operatorManifest.operators.flatMap((operator) =>
    [operator.name, ...(operator.aliases ?? [])]
      .map((name) => [normalizeName(name), operator]),
  ),
);
const profileSourceAsset = inventory.companies[0].assets.find(({ kind }) => kind === 'profile');

async function tracedAsset(kind, path) {
  const buffer = await readFile(resolve(repositoryRoot, path));
  return {
    kind,
    path,
    status: 'present',
    size: (await stat(resolve(repositoryRoot, path))).size,
    sha256: createHash('sha256').update(buffer).digest('hex'),
  };
}

const companies = [];
for (const profile of profiles) {
  const displayName = profile['公司名称'];
  const featured = featuredByName.get(normalizeName(displayName));
  const operator = operatorByName.get(normalizeName(displayName));
  const slug = featured?.slug ?? operator?.slug ?? slugify(displayName);
  const assets = featured
    ? featured.assets
    : [
        profileSourceAsset,
        ...(operator ? [await tracedAsset('map-and-project-type', `maps/${operator.dataFile}`)] : []),
      ];
  companies.push({
    slug,
    sourceId: profile.data_id,
    displayName,
    companyType: profile['公司类型'],
    country: profile['国家'],
    region: profile['地区'],
    business: profile['主营业务'],
    marketPosition: profile['市场定位'],
    website: profile['官方网站'],
    foundedYear: Number(profile['成立年份']),
    headquarters: profile['总部'],
    projectCount: operator?.projectCount ?? 0,
    countryCount: operator?.countryCount ?? 0,
    businessRegions: operator?.businessRegions?.length ? operator.businessRegions : [profile['地区']],
    isFeatured: Boolean(featured),
    assets,
  });
}
if (new Set(companies.map(({ slug }) => slug)).size !== companies.length) {
  throw new Error('Generated company slugs are not unique.');
}

const companyByName = new Map(
  companies.map((company) => [normalizeName(company.displayName), company.slug]),
);
const relatedReports = reportContext.window.INDUSTRY_REPORTS
  .map((report) => ({
    report,
    companySlugs: [...new Set(
      (report.companies ?? [])
        .map((name) => companyByName.get(normalizeName(name)))
        .filter(Boolean),
    )],
  }));

const lines = [
  '-- Generated by scripts/build-company-demo-seed.mjs. Do not edit by hand.',
  'begin;',
  '',
];

for (const company of companies) {
  lines.push(
    `insert into app_private.companies (` +
      `slug, source_id, display_name, company_type, country, region, business, market_position, ` +
      `website, founded_year, headquarters, project_count, country_count, business_regions, is_featured` +
    `) values (` +
      `${quote(company.slug)}, ${quote(company.sourceId)}, ${quote(company.displayName)}, ` +
      `${quote(company.companyType)}, ${quote(company.country)}, ${quote(company.region)}, ` +
      `${quote(company.business)}, ${quote(company.marketPosition)}, ${quote(company.website)}, ` +
      `${Number(company.foundedYear)}, ${quote(company.headquarters)}, ${company.projectCount}, ` +
      `${company.countryCount}, ${textArray(company.businessRegions)}, ${company.isFeatured}` +
    `) on conflict (slug) do update set ` +
      `source_id = excluded.source_id, display_name = excluded.display_name, ` +
      `company_type = excluded.company_type, country = excluded.country, region = excluded.region, ` +
      `business = excluded.business, market_position = excluded.market_position, ` +
      `website = excluded.website, founded_year = excluded.founded_year, ` +
      `headquarters = excluded.headquarters, project_count = excluded.project_count, ` +
      `country_count = excluded.country_count, business_regions = excluded.business_regions, ` +
      `is_featured = excluded.is_featured, ` +
      `updated_at = now();`,
  );
  for (const asset of company.assets) {
    lines.push(
      `insert into app_private.company_assets (` +
        `company_slug, kind, source_path, status, byte_size, sha256` +
      `) values (` +
        `${quote(company.slug)}, ${quote(asset.kind)}, ${quote(asset.path)}, ` +
        `${quote(asset.status)}, ${asset.size}, ${quote(asset.sha256)}` +
      `) on conflict (company_slug, kind) do update set ` +
        `source_path = excluded.source_path, status = excluded.status, ` +
        `byte_size = excluded.byte_size, sha256 = excluded.sha256;`,
    );
  }
}

lines.push('');
for (const { report, companySlugs } of relatedReports) {
  lines.push(
    `insert into app_private.related_information (` +
      `id, kind, title, subtitle, summary, industry, region, information_type, source_name, ` +
      `published_on, language, source_format, attachment_available, keywords` +
    `) values (` +
      `${quote(report.id)}, 'report', ${quote(report.title)}, ${nullable(report.subtitle)}, ` +
      `${quote(report.summary)}, ${quote(report.industry)}, ${quote(report.region)}, ` +
      `${quote(report.type)}, ${quote(report.source)}, ${quote(report.date)}::date, ` +
      `${quote(report.language)}, ${quote(report.format)}, false, ${textArray(report.keywords ?? [])}` +
    `) on conflict (id) do update set ` +
      `title = excluded.title, subtitle = excluded.subtitle, summary = excluded.summary, ` +
      `industry = excluded.industry, region = excluded.region, ` +
      `information_type = excluded.information_type, source_name = excluded.source_name, ` +
      `published_on = excluded.published_on, language = excluded.language, ` +
      `source_format = excluded.source_format, attachment_available = false, keywords = excluded.keywords;`,
  );
  for (const slug of companySlugs) {
    lines.push(
      `insert into app_private.company_related_information (company_slug, information_id) ` +
      `values (${quote(slug)}, ${quote(report.id)}) on conflict do nothing;`,
    );
  }
}

lines.push(
  '',
  `insert into app_private.profiles (user_id, email, status) values ` +
    `('00000000-0000-4000-8000-000000000030', 'company-demo@local.wison', 'active') ` +
    `on conflict (user_id) do update set status = 'active';`,
  `insert into app_private.user_roles (user_id, role_code) values ` +
    `('00000000-0000-4000-8000-000000000030', 'sales_bd') on conflict do nothing;`,
  '',
  'commit;',
  '',
);

const serialized = lines.join('\n');
if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== serialized) {
    throw new Error('Company demo seed is missing or stale. Run the seed builder.');
  }
} else {
  await writeFile(outputPath, serialized, 'utf8');
  console.log(`Wrote ${companies.length} companies and ${relatedReports.length} reports to ${outputPath}`);
}
